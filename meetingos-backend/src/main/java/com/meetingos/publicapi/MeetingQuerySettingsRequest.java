    public MeetingQuerySettingsRequest {
        /*
         * 新增签到开放开关后，旧前端或旧测试请求可能不会携带 checkinEnabled。
         * 这里默认开启，避免升级后把已经发布的自助签到入口误判为关闭。
         */
        if (checkinEnabled == null) {
            checkinEnabled = true;
        }
    }

